import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = new URL('../packages/view/src/internal/bidi/', import.meta.url);

const manifest = JSON.parse(await readFile(new URL('unicode-sources.json', root), 'utf8'));

const names = 'L R EN ES ET AN CS B S WS ON BN NSM AL LRO RLO LRE RLE PDF LRI RLI FSI PDI'.split(
  ' ',
);

const types = new Map(names.map((name, index) => [name, 1 << index]));

const aliases = new Map([
  ['Left_To_Right', 'L'],
  ['Right_To_Left', 'R'],
  ['Arabic_Letter', 'AL'],
  ['European_Terminator', 'ET'],
]);

async function source(name, path = name) {
  const bytes = process.argv[2]
    ? await readFile(join(process.argv[2], name))
    : Buffer.from(
        await (
          await fetch(`https://www.unicode.org/Public/${manifest.version}/ucd/${path}`)
        ).arrayBuffer(),
      );

  assert.equal(createHash('sha256').update(bytes).digest('hex'), manifest.sha256[name], name);

  return bytes;
}

const classes = (await source('DerivedBidiClass.txt', 'extracted/DerivedBidiClass.txt')).toString();

const values = new Uint32Array(0x110000);

function fill(range, property) {
  const [first, last = first] = range
    .trim()
    .split('..')
    .map((value) => Number.parseInt(value, 16));

  const type = types.get(aliases.get(property.trim()) ?? property.trim());
  assert.ok(type, property);
  values.fill(type, first, last + 1);
}

// Defaults are ordered from general to specific, then overridden by assigned data.
for (const match of classes.matchAll(/# @missing: ([^;]+); ([^\n]+)/g)) fill(match[1], match[2]);

for (const line of classes.split('\n')) {
  const data = line.split('#')[0].trim();

  if (data) fill(...data.split(';'));
}

const ranges = [];

for (let start = 0; start < values.length;) {
  let end = start + 1;

  while (end < values.length && values[end] === values[start]) end++;
  ranges.push(start, end, values[start]);
  start = end;
}

const brackets = [];

for (const line of (await source('BidiBrackets.txt')).toString().split('\n')) {
  const data = line.split('#')[0].trim();

  if (!data) continue;
  const [point, pair, kind] = data.split(';').map((value) => value.trim());
  brackets.push(Number.parseInt(point, 16), Number.parseInt(pair, 16), Number(kind === 'o'));
}

await writeFile(
  new URL('unicode-data.ts', root),
  [
    '// Generated by scripts/generate-bidi-data.mjs. Unicode ' + manifest.version + '.',
    '// Source checksums: unicode-sources.json. License: LICENSE-Unicode.txt.',
    `export const unicodeVersion = '${manifest.version}';`,
    '',
    `export const TYPES = {${names.map((name) => `${name}: ${types.get(name)}`).join(',')}};`,
    '',
    `export const classRanges = new Uint32Array([${ranges.join(',')}]);`,
    '',
    `export const bracketPairs = new Uint32Array([${brackets.join(',')}]);`,
    '',
  ].join('\n'),
);

for (const name of ['BidiTest.txt', 'BidiCharacterTest.txt'])
  await writeFile(new URL(`__tests__/fixtures/${name}.gz`, root), gzipSync(await source(name)));

const formatted = spawnSync(
  'pnpm',
  ['exec', 'oxfmt', '--write', fileURLToPath(new URL('unicode-data.ts', root))],
  { stdio: 'inherit' },
);

assert.equal(formatted.status, 0, 'Generated Unicode data formatting failed');
